"""The schema, read back from a migrated database, rendered three ways:

    schema/<schema>/<schema>.sql     the DDL as the database holds it (every non-system schema)
    py/fund_db/ops/rows.py           the ops tables as TypedDicts + the column registry fund_db.ops uses
    node/src/rows.ts                 the same, as TypeScript interfaces + registry for @fund/db

All three are GENERATED from the database the migrations built, never edited by hand:

    python -m fund_db schema --write     after adding a migration (against a migrated database)
    python -m fund_db schema --check     exits 1 when any of the three is stale (tests run this)

So the migrations stay the one source of truth and the snapshot + both typed layers cannot drift
from them without a red test.
"""
from __future__ import annotations

from pathlib import Path

from . import config

GENERATED = "GENERATED by `python -m fund_db schema --write` from a migrated database. Do not edit."
TYPED_SCHEMA = "ops"

# postgres type -> (python annotation, typescript type)
_TYPES = {
    "text": ("str", "string"),
    "bigint": ("int", "number"),
    "integer": ("int", "number"),
    "smallint": ("int", "number"),
    "double precision": ("float", "number"),
    "real": ("float", "number"),
    "boolean": ("bool", "boolean"),
    "jsonb": ("Any", "unknown"),
    "json": ("Any", "unknown"),
    "tsvector": ("str", "string"),
    "timestamp with time zone": ("datetime", "Date"),
}


def schemas(conn) -> list[str]:
    rows = conn.execute(
        "SELECT nspname FROM pg_namespace WHERE nspname NOT IN ('public', 'information_schema') "
        "AND nspname NOT LIKE 'pg\\_%' ORDER BY nspname").fetchall()
    return [r["nspname"] for r in rows]


def tables(conn, schema: str) -> list[dict]:
    """Every table in `schema` with its columns, primary key, indexes and constraints."""
    out = []
    for t in conn.execute(
            "SELECT c.oid, c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
            "WHERE n.nspname = %s AND c.relkind IN ('r', 'p') ORDER BY c.relname", (schema,)).fetchall():
        cols = conn.execute(
            "SELECT a.attname AS name, quote_ident(a.attname) AS qname, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull AS notnull, "
            "pg_get_expr(d.adbin, d.adrelid) AS dflt, a.attidentity AS ident, a.attgenerated AS gen "
            "FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum "
            "WHERE a.attrelid = %s AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum", (t["oid"],)).fetchall()
        pk = conn.execute(
            "SELECT a.attname, quote_ident(a.attname) AS qname FROM pg_index i JOIN LATERAL unnest(i.indkey) WITH ORDINALITY k(attnum, ord) ON true "
            "JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = k.attnum "
            "WHERE i.indrelid = %s AND i.indisprimary ORDER BY k.ord", (t["oid"],)).fetchall()
        cons = conn.execute(
            "SELECT conname, pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE conrelid = %s AND contype IN ('c', 'u', 'f', 'x') "
            "ORDER BY conname", (t["oid"],)).fetchall()
        idx = conn.execute(
            "SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = %s AND tablename = %s ORDER BY indexname",
            (schema, t["relname"])).fetchall()
        out.append({
            "name": t["relname"],
            "columns": [dict(c) for c in cols],
            "pk": [r["attname"] for r in pk],
            "qpk": [r["qname"] for r in pk],
            "constraints": [dict(c) for c in cons],
            "indexes": [dict(i) for i in idx if not i["indexname"].endswith("_pkey")],
        })
    return out


def render_sql(schema: str, tbls: list[dict]) -> str:
    lines = [f"-- {GENERATED}", f"-- The `{schema}` schema as the migrations leave it; read this, change migrations/.", "",
             f"CREATE SCHEMA {schema};", ""]
    for t in tbls:
        body = []
        for c in t["columns"]:
            s = f"  {c['qname']} {c['type']}"
            if c["ident"]:
                s += " GENERATED " + ("ALWAYS" if c["ident"] == "a" else "BY DEFAULT") + " AS IDENTITY"
            elif c["gen"]:
                s += f" GENERATED ALWAYS AS ({c['dflt']}) STORED"
            elif c["dflt"] is not None:
                s += f" DEFAULT {c['dflt']}"
            if c["notnull"]:
                s += " NOT NULL"
            body.append(s)
        if t["pk"]:
            body.append(f"  PRIMARY KEY ({', '.join(t['qpk'])})")
        for k in t["constraints"]:
            body.append(f"  CONSTRAINT {k['conname']} {k['def']}")
        lines.append(f"CREATE TABLE {schema}.{t['name']} (\n" + ",\n".join(body) + "\n);")
        for i in t["indexes"]:
            lines.append(i["indexdef"] + ";")
        lines.append("")
    return "\n".join(lines)


def _py_type(c: dict) -> str:
    base = _TYPES.get(c["type"])
    if base is None:
        raise ValueError(f"no python type for postgres type {c['type']!r}; add it to fund_db.schema._TYPES")
    return base[0] if c["notnull"] else f"Optional[{base[0]}]"


def _ts_type(c: dict) -> str:
    base = _TYPES.get(c["type"])
    if base is None:
        raise ValueError(f"no typescript type for postgres type {c['type']!r}; add it to fund_db.schema._TYPES")
    return base[1] if c["notnull"] else f"{base[1]} | null"


def _camel(name: str) -> str:
    return "".join(p.capitalize() for p in name.split("_"))


def _registry(tbls: list[dict]) -> dict:
    """{table: {columns, pk, json, bool, generated, defaults}} - what the generic ops layer checks against."""
    reg = {}
    for t in tbls:
        reg[t["name"]] = {
            "columns": [c["name"] for c in t["columns"]],
            "pk": t["pk"],
            "json": [c["name"] for c in t["columns"] if c["type"] in ("jsonb", "json")],
            "bool": [c["name"] for c in t["columns"] if c["type"] == "boolean"],
            "generated": [c["name"] for c in t["columns"] if c["gen"]],
            "identity": [c["name"] for c in t["columns"] if c["ident"]],
            "required": [c["name"] for c in t["columns"]
                         if c["notnull"] and c["dflt"] is None and not c["ident"] and not c["gen"]],
        }
    return reg


def render_py(tbls: list[dict]) -> str:
    import json
    lines = [f'"""{GENERATED}', "", f"One TypedDict per `{TYPED_SCHEMA}` table (a row as fund_db.ops returns it) and TABLES,",
             'the column registry the generic ops layer validates every identifier against."""',
             "from __future__ import annotations", ""]
    body: list[str] = []
    for t in tbls:
        body.append(f"class {_camel(t['name'])}Row(TypedDict):")
        for c in t["columns"]:
            if c["gen"]:
                continue
            body.append(f"    {c['name']}: {_py_type(c)}")
        body += ["", ""]
    text = "\n".join(body)
    if "datetime" in text:
        lines.append("from datetime import datetime")
    used = [n for n in ("Any", "Optional") if f": {n}" in text or f"[{n}]" in text or f"{n}[" in text]
    lines.append("from typing import " + ", ".join(used + ["TypedDict"]))
    lines += ["", ""] + body
    reg = json.dumps(_registry(tbls), indent=4)
    lines.append(f"TABLES: dict[str, dict[str, list[str]]] = {reg}")
    lines.append("")
    return "\n".join(lines)


def render_ts(tbls: list[dict]) -> str:
    import json
    lines = [f"// {GENERATED}", f"// One interface per `{TYPED_SCHEMA}` table (a row as @fund/db returns it) and TABLES,",
             "// the column registry the generic ops layer validates every identifier against.", ""]
    for t in tbls:
        lines.append(f"export interface {_camel(t['name'])}Row {{")
        for c in t["columns"]:
            if c["gen"]:
                continue
            lines.append(f"  {c['name']}: {_ts_type(c)}")
        lines += ["}", ""]
    names = " | ".join(f"'{t['name']}'" for t in tbls)
    lines.append(f"export type TableName = {names}")
    lines.append("")
    lines.append("export interface TableSpec { columns: string[]; pk: string[]; json: string[]; bool: string[]; "
                 "generated: string[]; identity: string[]; required: string[] }")
    lines.append("")
    lines.append(f"export const TABLES: Record<TableName, TableSpec> = {json.dumps(_registry(tbls), indent=2)}")
    lines.append("")
    lines.append("export interface Rows {")
    for t in tbls:
        lines.append(f"  {t['name']}: {_camel(t['name'])}Row")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def outputs(conn) -> dict[Path, str]:
    """Every generated file and the text it should hold for the database behind `conn`."""
    root = config.repo_root()
    out: dict[Path, str] = {}
    for s in schemas(conn):
        tbls = tables(conn, s)
        out[root / "schema" / s / f"{s}.sql"] = render_sql(s, tbls)
        if s == TYPED_SCHEMA:
            out[root / "py" / "fund_db" / "ops" / "rows.py"] = render_py(tbls)
            out[root / "node" / "src" / "rows.ts"] = render_ts(tbls)
    return out


def stale(conn) -> list[Path]:
    return [p for p, text in outputs(conn).items()
            if not p.exists() or p.read_text(encoding="utf-8").replace("\r\n", "\n") != text]


def write(conn) -> list[Path]:
    changed = stale(conn)
    for p, text in outputs(conn).items():
        if p in changed:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(text.encode("utf-8"))
    return changed
