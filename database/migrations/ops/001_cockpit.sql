-- ops 001: the cockpit's store, moved from SQLite (app/db/001..410, and the columns app/server
-- added at runtime: conversations.model/effort/indexed, law_loads.source) to PostgreSQL.
--
-- Carried over column for column, name for name, with these deliberate type changes:
--   * times stay epoch MILLISECONDS in bigint (every caller computes in ms; nothing is a timestamptz)
--   * a 0/1 INTEGER flag becomes boolean (forgotten, indexed, at_boot, ok, file_board, enabled,
--     armed, timed_out, forced, capped)
--   * a *_json TEXT column (and chat_prompts.tags, comparator_snapshots.series) becomes jsonb
--   * INTEGER PRIMARY KEY becomes bigint GENERATED BY DEFAULT AS IDENTITY (an import may carry ids)
--   * REAL becomes double precision
--   * the FTS5 table messages_fts becomes ops.messages with a generated tsvector and a GIN index
-- The data-fix migrations (005, 007, 410) are not repeated: they already ran on the rows the
-- importer carries over. No foreign keys: SQLite had none and the cockpit relies on that.

CREATE SCHEMA IF NOT EXISTS ops;

CREATE TABLE ops.conversations (
  id               text PRIMARY KEY,
  agent_id         text NOT NULL,
  title            text NOT NULL DEFAULT '',
  transcript_uuid  text,
  state            text NOT NULL DEFAULT 'idle',     -- live | waiting | idle | closed
  cwd              text,
  started_at       bigint NOT NULL,
  last_at          bigint NOT NULL,
  tokens_in        bigint NOT NULL DEFAULT 0,
  tokens_out       bigint NOT NULL DEFAULT 0,
  cost_usd         double precision NOT NULL DEFAULT 0,
  forgotten        boolean NOT NULL DEFAULT false,
  model            text,
  effort           text,
  indexed          boolean NOT NULL DEFAULT false
);
CREATE INDEX conversations_agent ON ops.conversations (agent_id, last_at DESC);
CREATE INDEX conversations_transcript ON ops.conversations (transcript_uuid);

CREATE TABLE ops.messages (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id  text NOT NULL,
  role             text NOT NULL,                    -- user | assistant
  ts               bigint NOT NULL,
  text             text NOT NULL,
  tsv              tsvector GENERATED ALWAYS AS (to_tsvector('simple', text)) STORED
);
CREATE INDEX messages_conv ON ops.messages (conversation_id, ts);
CREATE INDEX messages_tsv ON ops.messages USING gin (tsv);

CREATE TABLE ops.events (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts               bigint NOT NULL,
  kind             text NOT NULL,                    -- turn | tool | edit | commit | ask | error | job | health | process | board
  summary          text NOT NULL,
  agent_id         text,
  conversation_id  text,
  payload_json     jsonb
);
CREATE INDEX events_ts ON ops.events (ts DESC);
CREATE INDEX events_agent ON ops.events (agent_id, ts DESC);

CREATE TABLE ops.usage (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts               bigint NOT NULL,
  agent_id         text NOT NULL,
  conversation_id  text,
  model            text,
  tokens_in        bigint NOT NULL DEFAULT 0,
  tokens_out       bigint NOT NULL DEFAULT 0,
  cache_read       bigint NOT NULL DEFAULT 0,
  cache_write      bigint NOT NULL DEFAULT 0,
  cost_usd         double precision NOT NULL DEFAULT 0
);
CREATE INDEX usage_ts ON ops.usage (ts);

CREATE TABLE ops.presence (
  hand_id          text PRIMARY KEY,
  agent_id         text NOT NULL,
  conversation_id  text,
  doing            text,
  since            bigint NOT NULL,
  heartbeat_at     bigint NOT NULL,
  pid              integer
);

CREATE TABLE ops.health_readings (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts               bigint NOT NULL,
  probe_id         text NOT NULL,                    -- e.g. dash:trade/port, venue:exchange_a, system:selftest
  target           text NOT NULL,                    -- dashboard | venue | system | job
  status           text NOT NULL,                    -- ok | warn | fail | unknown
  reading          text,
  detail_json      jsonb
);
CREATE INDEX health_probe ON ops.health_readings (probe_id, ts DESC);

CREATE TABLE ops.job_runs (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id           text NOT NULL,
  due_at           bigint,
  started_at       bigint,
  ended_at         bigint,
  status           text NOT NULL,                    -- ok | fail | unknown | missed | skipped | running
  exit_code        integer,
  log_path         text,
  conversation_id  text,
  detail           text,
  trigger          text NOT NULL DEFAULT 'schedule', -- schedule | manual
  pid              integer
);
CREATE INDEX job_runs_job ON ops.job_runs (job_id, started_at DESC);
CREATE INDEX job_runs_due ON ops.job_runs (job_id, due_at);
CREATE INDEX job_runs_status ON ops.job_runs (status);

CREATE TABLE ops.processes (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dashboard_id     text NOT NULL,
  mode             text NOT NULL,                    -- prod | dev
  pid              integer,
  port             integer,
  cmd              text NOT NULL,
  started_at       bigint NOT NULL,
  stopped_at       bigint,
  exit_code        integer,
  log_path         text
);
CREATE INDEX processes_dash ON ops.processes (dashboard_id, started_at DESC);

CREATE TABLE ops.reads (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts               bigint NOT NULL,
  agent_id         text NOT NULL,
  conversation_id  text,
  book_path        text NOT NULL,
  at_boot          boolean NOT NULL DEFAULT false
);
CREATE INDEX reads_book ON ops.reads (book_path, ts DESC);
CREATE INDEX reads_agent ON ops.reads (agent_id, ts DESC);
CREATE INDEX reads_pull ON ops.reads (at_boot, ts DESC);

CREATE TABLE ops.commits (
  repo             text NOT NULL,
  sha              text NOT NULL,
  ts               bigint NOT NULL,
  author           text,                             -- a ROLE (the Agent: trailer, else 'you'), never a git author name
  agent_id         text,
  conversation_id  text,
  subject          text NOT NULL,
  files_json       jsonb,
  change_id        text,
  loop_change      text,
  shrink_json      jsonb,
  PRIMARY KEY (repo, sha)
);
CREATE INDEX commits_ts ON ops.commits (ts DESC);
CREATE INDEX commits_conv ON ops.commits (conversation_id);

CREATE TABLE ops.loop_metrics (
