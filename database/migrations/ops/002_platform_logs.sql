-- ops 002: logs that were files under the data root or the machine floor, moved into the ops
-- store so no repo writes its own log file (the data law: every repo through fund_db / @fund/db).
--
--   data_audit      fundplat's DATA panel audit (was <files>/crypto-store/ops-audit.jsonl):
--                   every delete / restore / purge and every refusal, append-only
--   wire_changes    venue changes the platform DETECTED (was <files>/crypto-store/wire/wire.jsonl)
--   wire_snapshots  each venue's latest public-metadata read per UTC day (was wire/snap/<v>/<day>.json)
--   wire_state      small named cursors of the wire job (was wire/state.json: special_scan_ms)
--   no_lesson       a desk stand-down that filed no lesson (was <floor>/no-lesson.jsonl; the
--                   cockpit's debt rule reads it)
--
-- Times are epoch MILLISECONDS in bigint, as everywhere in ops. before/after keep the value the
-- venue published (a number, a string or null) as jsonb, never coerced.

CREATE TABLE ops.data_audit (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts               bigint NOT NULL,
  op               text NOT NULL,                    -- delete.apply | delete.refused | restore | purge | ...
  actor            text NOT NULL,
  pid              integer,
  host             text,
  plan_id          text,
  request          jsonb,
  result           jsonb
);
CREATE INDEX data_audit_ts ON ops.data_audit (ts DESC, id DESC);

CREATE TABLE ops.wire_changes (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts_ms            bigint NOT NULL,                  -- the snapshot (or the special settlement) stamp
  prev_ms          bigint,                           -- the previous snapshot's stamp; null for a special
  venue            text NOT NULL,
  kind             text NOT NULL,                    -- list | delist | cadence | lev | fee | special
  subject          text NOT NULL,
  before           jsonb,
  after            jsonb,
  source           text NOT NULL DEFAULT '',
  tag              text NOT NULL DEFAULT '[API]',
  logged           bigint NOT NULL                   -- when the row was written
);
CREATE INDEX wire_changes_ts ON ops.wire_changes (ts_ms DESC, id DESC);
CREATE INDEX wire_changes_venue ON ops.wire_changes (venue, ts_ms DESC);

CREATE TABLE ops.wire_snapshots (
  venue            text NOT NULL,
  day              text NOT NULL,                    -- YYYY-MM-DD (UTC) of ts_ms
  ts_ms            bigint NOT NULL,
  source           text NOT NULL DEFAULT '',
  markets          jsonb NOT NULL,                   -- {subject: {cadence_h, lev, fee, ...}}
  PRIMARY KEY (venue, day)
);

CREATE TABLE ops.wire_state (
  key              text PRIMARY KEY,
  value            jsonb,
  updated          bigint NOT NULL
);

CREATE TABLE ops.no_lesson (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts               bigint NOT NULL,
  desk             text NOT NULL DEFAULT '.',
  hand             text,
  operator         text,
  subject          text NOT NULL DEFAULT '',
  reason           text NOT NULL DEFAULT '',
  touched          jsonb NOT NULL DEFAULT '[]'::jsonb
);
CREATE INDEX no_lesson_desk ON ops.no_lesson (desk, ts DESC);
